type T = 'alerta' | 'informacao' | 'oportunidade' | 'risco';

function mk(id: string, titulo: string, resumo: string, dominio: string, urgencia: U, tipo: T, acao: string): IntelligenceCard {
  return {
    id: `demo-${id}`,
    titulo, resumo,
    por_que_importa: '',
    onde_afeta: '',
    o_que_fazer: acao,
    dominio, area: dominio,
    urgencia, tipo_card: tipo,
    confianca: 'media',
    confianca_score: urgencia === 'alta' ? 0.82 : urgencia === 'media' ? 0.74 : 0.68,
    impacto: urgencia === 'alta' ? 'alto' : 'moderado',
    risco_erro: urgencia === 'alta' ? 0.25 : 0.35,
    _synthetic: true,
  };
}

